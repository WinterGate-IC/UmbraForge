@lru_cache(maxsize=1)
def font_path() -> str:
    override = os.environ.get("UMBRAFORGE_EMOJI_FONT", "").strip()
    if override and Path(override).is_file():
        return override
    for candidate in _FONT_CANDIDATES:
        if Path(candidate).is_file():
            return candidate
    return ""


def available() -> bool:
    return bool(font_path())


@lru_cache(maxsize=12)
def _font(size: int):
    path = font_path()
    if not path:
        return None
    try:
        return ImageFont.truetype(path, size)
    except (OSError, ValueError):
        return None


@lru_cache(maxsize=640)
def glyph_png(char: str, size: int = 96, color: str = "") -> bytes:
    """Return a square PNG of one emoji, optionally tinted to ``color``."""
    char = char or ""
    size = max(12, min(512, int(size)))
    font = _font(size)
    if not char or font is None:
        return b""
    pad = size
    canvas = Image.new("RGBA", (size * 3, size * 3), (0, 0, 0, 0))
    draw = ImageDraw.Draw(canvas)
    try:
        draw.text((pad, pad), char, font=font, embedded_color=True)
    except (ValueError, OSError, TypeError):
        try:
            draw.text((pad, pad), char, font=font, fill=(255, 255, 255, 255))
        except (ValueError, OSError):
            return b""
    bbox = canvas.getbbox()
    if not bbox:
        return b""
    glyph = canvas.crop(bbox)
    width, height = glyph.size
    scale = min(size / max(1, width), size / max(1, height))
    glyph = glyph.resize(
        (max(1, int(round(width * scale))), max(1, int(round(height * scale)))),
        Image.Resampling.LANCZOS)
    square = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    square.paste(glyph, ((size - glyph.width) // 2,
                         (size - glyph.height) // 2), glyph)
    if color:
        try:
            rgb = ImageColor.getrgb(color)[:3]
        except (ValueError, AttributeError):
            rgb = (255, 255, 255)
        tint = Image.new("RGBA", (size, size), (*rgb, 255))
        tint.putalpha(square.getchannel("A"))
        square = tint
    buffer = io.BytesIO()
    square.save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()


def preview_png(char: str, size: int = 72) -> bytes:
    return glyph_png(char, size)
