EMOJIS: tuple[Emoji, ...] = tuple(
    Emoji(char, name, category, keywords)
    for char, name, category, keywords in _RAW
)
BY_CHAR: dict[str, Emoji] = {item.char: item for item in EMOJIS}
CATEGORY_ORDER: tuple[str, ...] = (
    "Smileys", "People", "Nature", "Food", "Activity", "Travel", "Objects",
    "Symbols", "Flags",
)

_RECENT: list[str] = []


# --------------------------------------------------------------------------
# lookup
# --------------------------------------------------------------------------
def categories() -> list[str]:
    present = {item.category for item in EMOJIS}
    return [name for name in CATEGORY_ORDER if name in present]


def get(char: str) -> Emoji | None:
    return BY_CHAR.get(char or "")


def label(char: str) -> str:
    item = get(char)
    return item.name if item else "Emoji"


def describe(char: str) -> str:
    item = get(char)
    if item is None:
        return "Emoji"
    return f"{item.char}  {item.name}"


def entries(category: str | None = None,
            needle: str = "") -> list[Emoji]:
    """Return emoji matching an optional category and an AND-word search."""
    words = [word for word in (needle or "").casefold().split() if word]
    found: list[Emoji] = []
    for item in EMOJIS:
        if category and item.category != category:
            continue
        if words and not all(word in item.haystack for word in words):
            continue
        found.append(item)
    return found


def recent(limit: int = 14) -> list[Emoji]:
    result: list[Emoji] = []
    for char in _RECENT:
        item = get(char)
        if item is not None and item not in result:
            result.append(item)
        if len(result) >= limit:
            break
    return result


def remember(char: str) -> None:
    item = get(char)
    if item is None:
        return
    while item.char in _RECENT:
        _RECENT.remove(item.char)
    _RECENT.insert(0, item.char)
    del _RECENT[24:]


def clear_recent() -> None:
    _RECENT.clear()


